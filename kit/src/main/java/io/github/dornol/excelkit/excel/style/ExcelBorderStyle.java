package io.github.dornol.excelkit.excel.style;


/**
 * Predefined border styles for Excel cells.
 * <p>
 * A simplified set of border styles for configuring cell borders in {@link io.github.dornol.excelkit.excel.ExcelColumn.ExcelColumnBuilder}
 * and {@link io.github.dornol.excelkit.excel.ColumnConfig}.
 *
 * @author dhkim
 * @since 0.6.0
 */
public enum ExcelBorderStyle {

    /** No border. */
    NONE,
    /** Thin border. */
    THIN,
    /** Medium border. */
    MEDIUM,
    /** Thick border. */
    THICK,
    /** Dashed border. */
    DASHED,
    /** Dotted border. */
    DOTTED,
    /** Double border. */
    DOUBLE,
    /** Hairline border. */
    HAIR,
    /** Medium dashed border. */
    MEDIUM_DASHED,
    /** Dash-dot border. */
    DASH_DOT,
    ;

}
